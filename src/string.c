int strcmp(char *s1,char *s2)
    {
    while( *s1 && *s1==*s2 ) s1++,s2++;
    return *s1-*s2;
    }

/************************************************************************/
/************************************************************************/
int strncmp(char *s1,char *s2,int size)
    {
    while( *s1 && *s1==*s2 && --size > 0 ) s1++,s2++;
    return *s1-*s2;
    }

/************************************************************************/
